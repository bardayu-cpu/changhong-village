const vm = require('vm');
const fs = require('fs');
const assert = require('assert');
const hooks = {};
const ctx = {GameGlobal:{},wx:{onHide:fn=>hooks.hide=fn,onShow:fn=>hooks.show=fn}};
vm.createContext(ctx);
const code = fs.readFileSync('wxgame/kitchen-visibility.js','utf8');
vm.runInContext(code,ctx);
const state = ctx.GameGlobal.__suqiKitchenVisibility;
assert.strictEqual(state.hidden(),false);
assert.strictEqual(state.epoch(),0);
hooks.hide();
assert.strictEqual(state.hidden(),true);
assert.strictEqual(state.epoch(),1);
hooks.show();
assert.strictEqual(state.hidden(),false);
assert.strictEqual(state.epoch(),2);
vm.runInContext(code,ctx);
assert.strictEqual(ctx.GameGlobal.__suqiKitchenVisibility,state);
hooks.hide();
assert.strictEqual(state.epoch(),3);
console.log('RESULT PASS 前后台状态与重复加载');
